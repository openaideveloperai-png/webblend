// Builds one self-contained HTML file (no server needed):
//   index.html          full document - double-click to open, works offline
//   dist/artifact.html  same app as a page fragment for claude.ai artifact hosting
import fs from 'fs';
import path from 'path';
import { build } from 'esbuild';

const root = path.dirname(new URL(import.meta.url).pathname);
const r = (...p) => path.join(root, ...p);
const watch = process.argv.includes('--dev');

// 1) embed the Draco decoder so compressed glTF works offline
fs.mkdirSync(r('src/generated'), { recursive: true });
const dracoDir = r('node_modules/three/examples/jsm/libs/draco/gltf');
const wrapper = fs.readFileSync(path.join(dracoDir, 'draco_wasm_wrapper.js'), 'utf8');
const wasm = fs.readFileSync(path.join(dracoDir, 'draco_decoder.wasm')).toString('base64');
fs.writeFileSync(r('src/generated/draco-inline.js'),
  `// generated by build.mjs - do not edit\nexport const DRACO_WRAPPER_JS = ${JSON.stringify(wrapper)};\nexport const DRACO_WASM_B64 = ${JSON.stringify(wasm)};\n`);

// 2) bundle
const result = await build({
  entryPoints: [r('src/main.js')],
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: ['es2020', 'chrome90', 'firefox90', 'safari15'],
  minify: !watch,
  sourcemap: false,
  write: false,
  legalComments: 'none',
  define: {
    'import.meta.url': '"https://cdn.jsdelivr.net/npm/three@0.186.1/examples/jsm/loaders/x.js"',
    'process.env.NODE_ENV': '"production"',
  },
  logLevel: 'warning',
});
let js = result.outputFiles[0].text;
js = js.replace(/<\/script/gi, '<\\/script').replace(/<!--/g, '<\\!--');

const head = fs.readFileSync(r('src/head.html'), 'utf8');
const body = fs.readFileSync(r('src/body.html'), 'utf8');
const version = JSON.parse(fs.readFileSync(r('package.json'), 'utf8')).version;
const stamp = `<!-- WebBlend Animator ${version} · built ${new Date().toISOString().slice(0, 10)} · single-file build -->`;

const full = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">
<meta name="description" content="Browser 3D animator: import glb, fbx, obj, blend and more, animate with bones, keyframes and AI.">
${stamp}
${head}
</head>
<body>
${body}
<script>${js}</script>
</body>
</html>
`;
fs.writeFileSync(r('index.html'), full);

fs.mkdirSync(r('dist'), { recursive: true });
fs.writeFileSync(r('dist/artifact.html'), `${head}\n${body}\n<script>${js}</script>\n`);

const kb = (s) => (Buffer.byteLength(s) / 1024).toFixed(0) + ' KB';
console.log(`index.html ${kb(full)}  ·  dist/artifact.html  ·  js ${kb(js)}`);
