const { chromium } = require('playwright');
const path = require('path');
const [,, A, OUT] = process.argv;
(async () => {
  const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
  const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
  page.on('pageerror', (e) => console.log('PAGEERROR ' + e.message));
  page.on('console', (m) => { if (m.type() === 'error' || m.type() === 'warning') console.log('console.' + m.type() + ': ' + m.text().slice(0, 300)); });
  await page.goto('file://' + path.resolve(__dirname, '../index.html'));
  await page.waitForTimeout(1500);
  const probe = () => page.evaluate(() => { const a = window.webblend; const v = a.viewport; return { frame: v.renderer.info.render.frame, calls: v.renderer.info.render.calls, dirty: v.dirty, playing: a.transport.playing, t: +a.transport.time.toFixed(2), lost: !!v.contextLost, worldKids: a.world.children.map((c) => c.name), cam: v.camera.position.toArray().map((x) => +x.toFixed(2)) }; });
  console.log('start', JSON.stringify(await probe()));
  await page.waitForTimeout(1000);
  console.log('+1s  ', JSON.stringify(await probe()));
  await page.click('.menu-btn:has-text("File")');
  const [chooser] = await Promise.all([page.waitForEvent('filechooser'), page.click('.dd-item:has-text("Open files")')]);
  await chooser.setFiles([path.join(A, 'hero.glb')]);
  await page.waitForTimeout(2500);
  console.log('import', JSON.stringify(await probe()));
  await page.waitForTimeout(1000);
  console.log('+1s  ', JSON.stringify(await probe()));
  await page.screenshot({ path: path.join(OUT, 'render-dbg.png') });
  await browser.close();
})();
