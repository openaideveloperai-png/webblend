import * as THREE from 'three';
import { makeMannequin } from '../src/scene/primitives.js';
import { detectHumanoid, paramsToSpec, defaultParams, retargetClip } from '../src/anim/humanoid.js';
const root = makeMannequin();
const bones = []; root.traverse(o => o.isBone && bones.push(o));
const rig = detectHumanoid(root, bones);
if (!rig) { console.log('NOT DETECTED'); process.exit(1); }
console.log('map', Object.fromEntries(Object.entries(rig.map).map(([k,b])=>[k,b.name])));
console.log('hipHeight', rig.hipHeight.toFixed(3), 'up', rig.up.toArray(), 'lat', rig.lat.toArray(), 'fwd', rig.fwd.toArray());
const wp = (n) => new THREE.Vector3().setFromMatrixPosition(root.getObjectByName(n).matrixWorld);
let fails = 0;
const check = (label, cond) => { console.log((cond ? 'ok  ' : 'FAIL') + ' ' + label); if (!cond) fails++; };
const p = defaultParams();
rig.apply(rig.solve(paramsToSpec(p)));
check('neutral: left hand below shoulder & on left', wp('LeftHand').y < 1.0 && wp('LeftHand').x > 0.1);
check('neutral: right hand on right', wp('RightHand').x < -0.1);
check('neutral: elbow slightly forward bend -> hand forward of elbow', wp('LeftHand').z > wp('LeftForeArm').z - 0.001);
const p2 = { ...p, lLegSwing: 60, lKnee: 0 };
rig.apply(rig.solve(paramsToSpec(p2)));
check('left leg swing forward -> left foot forward', wp('LeftFoot').z > 0.3);
const p3 = { ...p, lKnee: 90 };
rig.apply(rig.solve(paramsToSpec(p3)));
check('left knee bend -> foot goes back', wp('LeftFoot').z < -0.2);
const p4 = { ...p, spinePitch: 40 };
rig.apply(rig.solve(paramsToSpec(p4)));
check('spine pitch + -> head forward', wp('Head').z > 0.2);
const p5 = { ...p, headYaw: 60 };
rig.apply(rig.solve(paramsToSpec(p5)));
const hq = new THREE.Vector3(0,0,1).applyQuaternion(root.getObjectByName('Head').getWorldQuaternion(new THREE.Quaternion()));
check('head yaw + -> faces character left (+x)', hq.x > 0.5);
const p6 = { ...p, rArmRaise: 90, rElbow: 80, rElbowUp: 1 };
rig.apply(rig.solve(paramsToSpec(p6)));
check('wave pose: right hand above elbow', wp('RightHand').y > wp('RightForeArm').y + 0.15);
const p7 = { ...p, hipsY: -0.3 };
rig.apply(rig.solve(paramsToSpec(p7)));
check('hipsY -0.3 lowers hips', Math.abs(wp('Hips').y - (0.95 - 0.3 * rig.hipHeight)) < 0.01);
const p8 = { ...p, lArmRaise: 10, lArmSwing: 80, lElbow: 0 };
rig.apply(rig.solve(paramsToSpec(p8)));
check('arm swing forward -> hand in front', wp('LeftHand').z > 0.35);
// bake + retarget onto a second mannequin with rotated bones (simulate different rig conventions)
const clip = rig.bake('test', 1, (t) => paramsToSpec({ ...p, lLegSwing: 40 * Math.sin(t * Math.PI * 2), rArmRaise: 90 }));
console.log('baked tracks', clip.tracks.length, 'keys', clip.tracks[0].times.length);
const root2 = makeMannequin('B');
// give B different local bone orientations but same rest shape
root2.traverse(o => { if (o.isBone && o.parent && o.parent.isBone) { /* keep */ } });
root2.scale.setScalar(0.01); root2.updateMatrixWorld(true);
const bones2 = []; root2.traverse(o => o.isBone && bones2.push(o));
const rig2 = detectHumanoid(root2, bones2);
const rt = retargetClip(rig, clip, rig2);
const mixer = new THREE.AnimationMixer(root2); mixer.clipAction(rt).play(); mixer.setTime(0.25); root2.updateMatrixWorld(true);
const lf = new THREE.Vector3().setFromMatrixPosition(root2.getObjectByName('LeftFoot').matrixWorld);
check('retarget onto 1/100 scale rig: left foot forward at t=.25', lf.z > 0.002);
const rh = new THREE.Vector3().setFromMatrixPosition(root2.getObjectByName('RightHand').matrixWorld);
check('retarget: right arm raised to side', rh.y > 0.0135 && rh.x < -0.006);
console.log(fails ? fails + ' FAILURES' : 'ALL OK');
